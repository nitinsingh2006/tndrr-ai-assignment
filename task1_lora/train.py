"""
train.py
--------
Fine-tune HuggingFaceTB/SmolLM2-360M-Instruct with LoRA on the synthetic
plain-English → JSON dataset generated by generate_dataset.py.

LoRA hyperparameter rationale (see also lora_config.json):
  r=8              Rank 8 gives good capacity for a simple 4-field JSON task
  lora_alpha=16    alpha=2*r is a standard heuristic for stable training
  target_modules   q_proj & v_proj capture instruction-following patterns
  lora_dropout=0.05  Light regularisation on a 1 000-sample dataset
  lr=2e-4          Standard LoRA learning rate from the original paper
  epochs=3         3 passes is sufficient; more risks memorisation on 1 k samples
  batch_size=4     Fits in ~4 GB VRAM; gradient_accumulation gives effective 16
"""

import json
import os
import sys

import torch
from datasets import Dataset, load_dataset
from peft import LoraConfig, TaskType, get_peft_model
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    DataCollatorForSeq2Seq,
    Trainer,
    TrainingArguments,
)

# ── Paths ──────────────────────────────────────────────────────────────────────
BASE_DIR   = os.path.dirname(os.path.abspath(__file__))
DATA_DIR   = os.path.join(BASE_DIR, "data")
OUTPUT_DIR = os.path.join(BASE_DIR, "lora_model")

TRAIN_PATH = os.path.join(DATA_DIR, "train.jsonl")
TEST_PATH  = os.path.join(DATA_DIR, "test.jsonl")

# ── Model ──────────────────────────────────────────────────────────────────────
MODEL_NAME = "HuggingFaceTB/SmolLM2-360M-Instruct"

# ── Training hyper-parameters ──────────────────────────────────────────────────
LORA_R          = 8      # rank — balance of capacity vs trainable params
LORA_ALPHA      = 16     # 2*r heuristic for stable gradient magnitudes
LORA_DROPOUT    = 0.05   # small dropout prevents overfitting on 1 k examples
TARGET_MODULES  = ["q_proj", "v_proj"]  # attention projections

LR                       = 2e-4   # standard LoRA learning rate
EPOCHS                   = 3      # 3 epochs; more risks memorisation
BATCH_SIZE               = 4      # fits 4 GB VRAM with gradient checkpointing
GRAD_ACCUM               = 4      # effective batch = 16
MAX_SEQ_LENGTH           = 256
WARMUP_STEPS             = 50
SEED                     = 42


# ── Helpers ────────────────────────────────────────────────────────────────────
def _build_prompt(example: dict, tokenizer) -> str:
    """
    Format a dataset example into a model-ready string.
    Uses the tokenizer's chat template when available, falls back to a simple
    "Input: … Output: …" format.
    """
    user_msg = example["input"]
    asst_msg = example["output"]

    if hasattr(tokenizer, "apply_chat_template") and tokenizer.chat_template:
        messages = [
            {"role": "user",      "content": user_msg},
            {"role": "assistant", "content": asst_msg},
        ]
        return tokenizer.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=False
        )
    return f"Input: {user_msg}\nOutput: {asst_msg}"


def tokenize(batch: dict, tokenizer) -> dict:
    """Tokenise a batch of prompts with truncation and padding."""
    texts = [_build_prompt({"input": inp, "output": out}, tokenizer)
             for inp, out in zip(batch["input"], batch["output"])]
    encoded = tokenizer(
        texts,
        truncation=True,
        max_length=MAX_SEQ_LENGTH,
        padding=False,
    )
    encoded["labels"] = [ids[:] for ids in encoded["input_ids"]]
    return encoded


# ── Main ───────────────────────────────────────────────────────────────────────
def main() -> None:
    # ── 0. Verify data exists ──────────────────────────────────────────────────
    if not os.path.isfile(TRAIN_PATH):
        sys.exit(
            f"[ERROR] {TRAIN_PATH} not found. "
            "Run generate_dataset.py first."
        )

    # ── 1. Load tokenizer & base model ────────────────────────────────────────
    print(f"Loading tokeniser & model: {MODEL_NAME}")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        MODEL_NAME,
        torch_dtype=torch.float32,     # fp32 for CPU / small GPU compatibility
        trust_remote_code=True,
    )
    # Enable gradient checkpointing to reduce VRAM usage
    model.enable_input_require_grads()
    model.gradient_checkpointing_enable()

    # ── 2. Apply LoRA ──────────────────────────────────────────────────────────
    print("Applying LoRA adapters …")
    lora_cfg = LoraConfig(
        task_type    = TaskType.CAUSAL_LM,
        r            = LORA_R,
        lora_alpha   = LORA_ALPHA,
        target_modules = TARGET_MODULES,
        lora_dropout = LORA_DROPOUT,
        bias         = "none",
    )
    model = get_peft_model(model, lora_cfg)
    model.print_trainable_parameters()

    # ── 3. Load & tokenise dataset ─────────────────────────────────────────────
    print("Loading dataset …")
    raw = load_dataset(
        "json",
        data_files={"train": TRAIN_PATH, "test": TEST_PATH},
    )

    tokenized = raw.map(
        lambda batch: tokenize(batch, tokenizer),
        batched=True,
        remove_columns=raw["train"].column_names,
    )

    # ── 4. Training arguments ──────────────────────────────────────────────────
    training_args = TrainingArguments(
        output_dir                  = OUTPUT_DIR,
        num_train_epochs            = EPOCHS,
        per_device_train_batch_size = BATCH_SIZE,
        gradient_accumulation_steps = GRAD_ACCUM,
        learning_rate               = LR,
        warmup_steps                = WARMUP_STEPS,
        lr_scheduler_type           = "cosine",
        optim                       = "adamw_torch",
        fp16                        = torch.cuda.is_available(),  # fp16 on GPU
        logging_steps               = 50,
        save_strategy               = "epoch",
        evaluation_strategy         = "epoch",
        load_best_model_at_end      = True,
        metric_for_best_model       = "eval_loss",
        seed                        = SEED,
        report_to                   = "none",          # no wandb / TB needed
        dataloader_num_workers      = 0,
    )

    # ── 5. Train ───────────────────────────────────────────────────────────────
    data_collator = DataCollatorForSeq2Seq(
        tokenizer, model=model, padding=True, pad_to_multiple_of=8
    )

    trainer = Trainer(
        model           = model,
        args            = training_args,
        train_dataset   = tokenized["train"],
        eval_dataset    = tokenized["test"],
        data_collator   = data_collator,
        tokenizer       = tokenizer,
    )

    print("Starting training …")
    trainer.train()

    # ── 6. Save adapter + config ───────────────────────────────────────────────
    print(f"Saving LoRA adapter to {OUTPUT_DIR} …")
    model.save_pretrained(OUTPUT_DIR)
    tokenizer.save_pretrained(OUTPUT_DIR)

    # Persist the training config alongside the adapter
    config_path = os.path.join(BASE_DIR, "lora_config.json")
    cfg = {
        "model":    MODEL_NAME,
        "task":     "text-to-JSON (action, item, quantity, date)",
        "lora": {
            "r":              LORA_R,
            "lora_alpha":     LORA_ALPHA,
            "target_modules": TARGET_MODULES,
            "lora_dropout":   LORA_DROPOUT,
            "bias":           "none",
            "task_type":      "CAUSAL_LM",
            "reason_r":          "Rank 8 is enough capacity for a simple 4-field JSON format task",
            "reason_alpha":      "alpha=2*r is a standard heuristic that keeps gradients stable",
            "reason_modules":    "q_proj and v_proj in attention capture instruction-following patterns",
            "reason_dropout":    "0.05 prevents overfitting on the 1000-sample dataset",
            "reason_lr":         "2e-4 is the standard LoRA learning rate from the original paper",
            "reason_epochs":     "3 epochs is enough; more risks memorization on small dataset",
            "reason_batch":      "Batch 4 with grad_accum 4 = effective 16, fits 4GB VRAM",
        },
        "training": {
            "learning_rate":               LR,
            "epochs":                      EPOCHS,
            "batch_size":                  BATCH_SIZE,
            "gradient_accumulation_steps": GRAD_ACCUM,
            "max_seq_length":              MAX_SEQ_LENGTH,
            "warmup_steps":                WARMUP_STEPS,
            "optimizer":                   "adamw_torch",
        },
    }
    with open(config_path, "w") as fh:
        json.dump(cfg, fh, indent=2)

    print(f"✓ Training complete. Adapter saved to {OUTPUT_DIR}")
    print(f"✓ Config saved to {config_path}")


if __name__ == "__main__":
    main()
